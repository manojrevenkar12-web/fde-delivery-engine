"""The service's demo data: the engine's own run of a demo year, cut at mid-year, holding only what a delivery
manager sees (scopes, logged hours, status notes as written, plans, pipelines awaiting review). No truth goes in."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from fde.config import load
from fde.eval.run import run_design
from fde.world import pipelines
from fde.world.world import World

WEEK = 30


def build(root: Path) -> dict[str, Any]:
    catalog, product, designs = load("catalog.json", root), load("product.json", root), load("designs.json", root)
    cfg = json.loads((root / "config" / "world.json").read_text(encoding="utf-8"))
    cfg["seed"] = "demo-seed"
    t, w = run_design(root, "", "engine", designs["designs"]["engine"], catalog, product, designs, snapshot_at=WEEK,
                      world_cfg=cfg)
    snap = t.snapshot
    assert snap is not None
    states = snap["states"]
    out_eng = []
    for eid, st in sorted(states.items()):
        e = st.engagement
        out_eng.append({
            "id": e.id, "customer": e.customer, "sector": e.sector, "topology": e.topology, "contract": e.contract,
            "fixedFee": e.fixed_fee, "startWeek": e.start_week, "requiredSkills": sorted(e.required_skills),
            "workItems": list(e.work_items),
            "phases": {p: {"scopedHours": s.scoped_hours, "dueWeek": s.due_week} for p, s in e.phases.items()},
            "phase": st.phase, "done": st.done, "logged": {k: round(v) for k, v in st.logged.items()},
            "reportedDone": st.reported_done, "dueExtension": st.due_extension, "escalatedWeek": st.escalated_week,
            "notes": [{"week": wk, "text": tx} for wk, tx in snap["notes"].get(eid, [])[-6:]],
            "gate": snap["gates"].get(eid),
        })
    # Pipelines waiting for go-live review: the deployed config, the indexed documents and the customer's golden set.
    review = []
    live = [s for s in states.values() if not s.done and s.phase in ("build", "go_live")]
    for st in sorted(live, key=lambda s: s.engagement.id)[:4]:
        job = next(j for j in w.jobs if j.id == st.engagement.id)
        dep = pipelines.build(w, job, [])
        review.append({"engagementId": job.id, "topology": job.topology, "config": dep.config,
                       "documents": [{"id": d.id, "content": d.content, "department": d.department}
                                     for d in dep.documents],
                       "golden": [{"question": q.question, "fact": q.fact, "sourceId": q.source_id}
                                  for q in dep.golden]})
    lib = snap["library"]
    return {
        "_about": "Generated by python -m fde.eval.cli seed from the engine's run of a demo year, cut at week "
                  f"{WEEK}. Only what a delivery manager sees.",
        "week": WEEK,
        "roster": [{"id": p.id, "name": p.name, "profile": p.profile, "skills": sorted(p.skills),
                    "capacityHours": p.capacity} for p in w.people],
        "engagements": out_eng,
        "plan": [{"fdeId": a.fde_id, "engagementId": a.engagement_id, "phase": a.phase, "hours": a.hours}
                 for a in snap["plan"].assignments],
        "hotStreaks": snap["hot"],
        "patterns": {"seen": {k: sorted(v) for k, v in lib.seen.items()}, "templates": sorted(lib.templates)},
        "escalations": [{"engagementId": e, "week": wk, "kind": k} for e, wk, k in snap["escalations"]],
        "declined": snap["declined"],
        "reviews": review,
    }
