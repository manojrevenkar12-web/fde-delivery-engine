import { api } from '../../shared/api.ts'
import { pct } from '../../shared/format.ts'
import type { Report } from '../../shared/types.ts'
import { useResource } from '../../shared/useResource.ts'
import { EmptyState, ErrorState, Skeleton } from '../../shared/ui/States.tsx'
import styles from './Results.module.css'

const ORDER = ['engine', 'by_hand', 'first_free', 'engine_no_gate', 'engine_no_escalation', 'engine_no_patterns', 'engine_accept_all']

export function ResultsTable({ report }: { report: Report }) {
  return (
    <table className={styles.table}>
      <caption>
        A simulated year: {report.world.engagements} opportunities, {report.world.people} people, the same work and the
        same luck for every design
      </caption>
      <thead>
        <tr>
          <th scope="col">Design</th>
          <th scope="col">Milestones on plan</th>
          <th scope="col">Surprise slips</th>
          <th scope="col">Utilization</th>
          <th scope="col">Weeks above 90%</th>
          <th scope="col">Incidents</th>
          <th scope="col">Margin</th>
        </tr>
      </thead>
      <tbody>
        {ORDER.filter((k) => report.designs[k]).map((k) => {
          const d = report.designs[k]
          return (
            <tr key={k} className={k === 'engine' ? styles.ours : undefined}>
              <th scope="row">{d.label}</th>
              <td>
                <span className={styles.bar}>
                  <span className={styles.fill} style={{ inlineSize: `${d.milestonesOnPlan * 100}%` }} />
                </span>
                {pct(d.milestonesOnPlan)}
              </td>
              <td>{d.surpriseSlips}</td>
              <td>{pct(d.utilization)}</td>
              <td>{d.burnoutWeeks}</td>
              <td>{d.productionIncidents}</td>
              <td>{pct(d.marginShare, 1)}</td>
            </tr>
          )
        })}
      </tbody>
    </table>
  )
}

export function ResultsView() {
  const { data, error, loading, retry } = useResource(() => api.results(), [])
  return (
    <section className={styles.view} aria-label="Results">
      <h1 className={styles.title}>How the engine compares</h1>
      <p className={styles.lede}>Generated by the evaluation on a simulated services year, not typed in.</p>
      {loading && !data ? <Skeleton label="Loading results" /> : null}
      {error ? <ErrorState what="The results" message={error} onRetry={retry} /> : null}
      {data && !data.dev ? <EmptyState title="No report yet." hint="Run python -m fde.eval.cli evaluate." /> : null}
      {data?.dev ? <ResultsTable report={data.dev} /> : null}
      {data?.heldout ? (
        <>
          <h2 className={styles.subtitle}>Held-out year, run once</h2>
          <ResultsTable report={data.heldout} />
        </>
      ) : null}
    </section>
  )
}
